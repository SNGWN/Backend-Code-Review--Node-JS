const BY_ID = new Map<string, RuleDefinition>(RULES.map((rule) => [rule.id, rule]));

export function getRule(id: string): RuleDefinition | undefined {
  return BY_ID.get(id);
}

export function listRules(): RuleDefinition[] {
  return [...RULES];
}

export function isHeuristic(ruleId: string): boolean {
  return BY_ID.get(ruleId)?.heuristic === true;
}

const SEVERITY_RANK: Record<Severity, number> = {
  CRITICAL: 4,
  HIGH: 3,
  MEDIUM: 2,
  LOW: 1,
  INFO: 0,
};

export function severityAtLeast(value: Severity, threshold: Severity): boolean {
  return SEVERITY_RANK[value] >= SEVERITY_RANK[threshold];
}

export function severityRank(value: Severity): number {
  return SEVERITY_RANK[value];
}
