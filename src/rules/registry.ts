import { IssueCategory, Severity } from '../types';

/**
 * Stable rule definitions. Every finding emitted by the scanner references a `ruleId`
 * defined here. The registry is the single source of truth for:
 *   - SARIF `reportingDescriptors` (rules block)
 *   - Baseline fingerprinting
 *   - `--disable-rule`, `--min-severity` filtering
 *   - CWE / OWASP taxonomies surfaced in reports
 *
 * Rule IDs are stable contract — never renumber or rename an existing id. Add new ids
 * and deprecate old ones via the optional `deprecated` flag below.
 */
export interface RuleDefinition {
  id: string;
  title: string;
  category: IssueCategory;
  defaultSeverity: Severity;
  cwe: string[];
  owasp: string;
  description: string;
  recommendation: string;
  /**
   * Heuristic rules fire on weaker signals (regex/keyword-only) and are off by default.
   * They surface only with `--enable-heuristics`.
   */
  heuristic?: boolean;
  /**
   * Mark true to keep the rule in the catalog but exclude it from emit. Useful when a
   * detector has been retired but ids must remain reserved for baseline stability.
   */
  deprecated?: boolean;
}

